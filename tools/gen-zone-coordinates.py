#!/usr/bin/env python3
"""Generates src/main/resources/geo/zone-coordinates.tsv: the approximate position of
every IANA time zone (the principal city listed in tzdata's zone1970.tab / zone.tab),
plus the backward-compatible link aliases from tzdata.zi (e.g. Asia/Calcutta,
US/Eastern). The app uses it to place the map when no other location is known; it
never leaves the computer. tzdata is in the public domain.

usage: python3 tools/gen-zone-coordinates.py [zoneinfo-dir] > src/main/resources/geo/zone-coordinates.tsv
       (zoneinfo-dir defaults to /usr/share/zoneinfo)
"""
import os
import re
import sys

ZONEINFO = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo'


def iso6709(text):
    m = re.fullmatch(r'([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?', text)
    if not m:
        raise ValueError('bad ISO 6709 coordinate: ' + text)
    sign = lambda c: -1 if c == '-' else 1
    lat = sign(m[1]) * (int(m[2]) + int(m[3]) / 60 + int(m[4] or 0) / 3600)
    lon = sign(m[5]) * (int(m[6]) + int(m[7]) / 60 + int(m[8] or 0) / 3600)
    return round(lat, 4), round(lon, 4)


def main():
    rows = {}
    for name in ('zone1970.tab', 'zone.tab'):
        with open(os.path.join(ZONEINFO, name), encoding='utf-8') as f:
            for line in f:
                if line.startswith('#') or not line.strip():
                    continue
                parts = line.rstrip('\n').split('\t')
                rows.setdefault(parts[2], iso6709(parts[1]))
    links = {}
    version = 'unknown'
    with open(os.path.join(ZONEINFO, 'tzdata.zi'), encoding='utf-8') as f:
        for line in f:
            if line.startswith('# version '):
                version = line.split()[2]
            if line.startswith('L '):
                _, target, alias = line.split()
                links[alias] = target
    out = sys.stdout
    out.write('# Approximate position of each IANA time zone: zone<TAB>latitude<TAB>longitude\n')
    out.write('# Source: IANA tzdata %s (zone1970.tab, zone.tab, link aliases from tzdata.zi), public domain.\n'
              % version)
    out.write('# Generated by tools/gen-zone-coordinates.py; do not edit by hand.\n')
    for zone in sorted(rows):
        out.write('%s\t%s\t%s\n' % (zone, rows[zone][0], rows[zone][1]))
    for alias in sorted(links):
        target = links[alias]
        while target in links and target not in rows:
            target = links[target]
        if target in rows and alias not in rows:
            out.write('%s\t%s\t%s\n' % (alias, rows[target][0], rows[target][1]))


if __name__ == '__main__':
    main()
